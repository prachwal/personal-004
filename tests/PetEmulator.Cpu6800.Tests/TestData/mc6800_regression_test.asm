; MC6800 regression binary source.
; The bytes below are assembled by ASxxxx (sdas6808) as data.  This keeps
; the source independent of the HC08 mnemonic/opcode differences while the
; emitted image remains an exact MC6800 program.
;
; Build:
;   sdas6808 -lo mc6800_regression_test.asm
;   sdld6808 -i -b CODE=0x0100 mc6800_regression_test
;   objcopy -I ihex -O binary mc6800_regression_test.ihx mc6800-functional-test.bin
;
; The harness loads the binary at $0100 and installs the reset vector.
; $0200 is the failure code: zero means success.  The program ends in WAI.

.module mc6800_regression_test
.area CODE (ABS)
.org 0x0100

; CLR/STX/CPX, stack setup, direct and conditional branch checks.
.db 0x7f,0x02,0x00,0xce,0x30,0x00,0x35,0xce,0x12,0x34,0xdf,0x10,0xde,0x10,0x8c,0x12
.db 0x34,0x26,0x4f,0x86,0x00,0x27,0x02,0x20,0x4f,0x86,0xff,0x8b,0x01,0x25,0x02,0x20

; DAA, indexed A/B load/store, PSHA/PULA.
.db 0x4d,0x86,0x09,0x8b,0x01,0x19,0xb7,0x02,0x01,0xce,0x20,0x00,0x86,0x42,0xa7,0x05
.db 0xa6,0x05,0xb7,0x02,0x02,0xc6,0x24,0xe7,0x06,0x36,0x4f,0x32,0xb7,0x02,0x03,0x86

; Extended INC, X increment/decrement, TAB/TBA, ASLA, success WAI.
.db 0xff,0xb7,0x02,0x04,0x7c,0x02,0x04,0xb6,0x02,0x04,0x27,0x02,0x20,0x26,0xce,0x00
.db 0x00,0x08,0x09,0xff,0x02,0x05,0x86,0x55,0x16,0x17,0xb7,0x02,0x06,0x48,0xb7,0x02
.db 0x07,0x3e

; Failure handlers: code 1..4 followed by STAA $0200 and WAI.
.db 0x86,0x01,0xb7,0x02,0x00,0x3e,0x86,0x02,0xb7,0x02,0x00,0x3e,0x86,0x03,0xb7,0x02
.db 0x00,0x3e,0x86,0x04,0xb7,0x02,0x00,0x3e
